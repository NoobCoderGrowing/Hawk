package hawk.cloud.recall;

/**
 * 本节点**服务不了当前索引版本** —— text-recall 与 vector-recall 共用这一个信号。
 * 两种情形都走它，因为**调用方该做的处置是同一个**：
 * <ul>
 *   <li><b>还没装过任何版本</b> —— 拉取任务还没跑到，索引目录是空的。拉取模型下的**常态**，
 *       每个新起的召回副本都要经历从启动到第一次拉到索引的那个周期。</li>
 *   <li><b>装上了但打不开</b> —— 文件损坏、字段定义变了读不出来、或者（向量侧）
 *       本节点的模型与建索引时那份**指纹不符**。这是部署问题，不是"还没到"。</li>
 * </ul>
 * 两种情况都应该让协调器**换一个副本重试**，所以都映射成 **HTTP 503**。
 * 具体是哪一种，看 {@link #getMessage()}。
 *
 * <h2>为什么绝不能退化成一个"空结果"</h2>
 * 如果这时返回 200 + 空结果，协调器就**分不出**「这一片服务不了」和「这一片确实没匹配」，
 * 于是悄悄把这一片算成 0 条命中 —— 结果是**静默少了 1/分片数 的语料**，
 * 而返回的 top-10 看起来完全正常。轮询还会把流量分给这种节点（3 副本时约 1/3 概率踩上）。
 *
 * <p>方案见 {@code DESIGN.md} §5.8.1。
 *
 * <p>名字取的是"没有可用的索引"这个更宽的意思 —— **不是**"索引不存在"。
 */
public class NoIndexException extends RuntimeException {

    public NoIndexException(String message) {
        super(message);
    }
}
