package hawk.recall.search;

/**
 * 这次检索**要不要打分**、要多少分。
 *
 * <p>存在的理由是省掉无用的计算。旧实现无条件算分 —— 连数值区间查询都会为每条命中
 * 造一个分数恒为 0 的 {@code ScoreDoc}，而这类查询恰恰是"只要 docID 列表"的。
 *
 * <p>把它做成**调用方显式声明**的参数，而不是靠查询树去猜：同一个查询，
 * 分页取前 20 条和要全量导出，需要的打分强度完全不同。
 */
public enum ScoreMode {

    /**
     * 完全不算分。只产出 docID 与总数。
     *
     * <p>给"筛选"类查询用（配合 {@code Occur.FILTER}）：数值区间、精确过滤、集合求交。
     * 省掉的是整条打分链路，不是零头。
     */
    NO_SCORES,

    /**
     * 只精确算**最终会被返回的那 top-K** 需要的分。
     *
     * <p>允许执行层用块最大分（block-max）之类的办法跳过必然进不了前 K 的文档。
     * 分页场景的默认选择。
     */
    TOP_SCORES,

    /**
     * 全量精确算分。
     *
     * <p>当你需要**所有**命中文档的准确分数时才用（例如要二次排序、要归并多个检索源的分数）。
     */
    COMPLETE;

    /** 是否需要分数。 */
    public boolean needsScores() {
        return this != NO_SCORES;
    }
}
